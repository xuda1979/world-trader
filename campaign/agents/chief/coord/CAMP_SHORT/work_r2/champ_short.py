    tr = (-1.9 * y.diff() + y / ANN).dropna()
    sig = (tr.rolling(378).mean() > 0).astype(float)
    W = sig.iloc[::42].reindex(tr.index).ffill().fillna(0.0)
    out['a6r7'] = pd.Series(0.0, index=W.index)          # long-only: short frac == 0
    # QAxasts: 5-leg TSMOM sign(panel - MA189), EW 20% -> shorts are legs with sign<0
