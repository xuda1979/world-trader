def champ_tier_delta(Wg: pd.DataFrame, expo: dict, base_rate: dict, tier_rate: float) -> pd.Series:
    """Champion-level daily tier delta = sum over slots of tier_delta_cost on the slot's
    measured short notional (|slot weight| x exposure fraction), moving from that slot's
    already-charged base rate to `tier_rate`. Fail-closed via tier_delta_cost."""
    total = None
    for n in Wg.columns:
        if n not in expo:
            continue
        if n not in base_rate:
            continue          # REALISTIC: no explicit base rate -> slot untouched
        sn = (Wg[n].abs() * expo[n].reindex(Wg.index).fillna(0.0)).rename(None)
        d = tier_delta_cost(sn, base_rate[n], tier_rate)
        total = d if total is None else total + d
    if total is None:
        total = pd.Series(0.0, index=Wg.index)
    return total.rename(None)
