def load_sleeve(p, pin_git_head: bool = True):
    """Load a sleeve CSV. pin_git_head=True (default) reads the GIT-COMMITTED blob — the
    champion is the committed artifact, so its stress tests must be reproducible from the
    committed inputs, immune to working-tree regeneration by other agents (4 champion
    input sleeves were regenerated by CAMP_COST's costfix after champion commit). Set
    pin_git_head=False to audit the live working tree instead."""
    if not pin_git_head:
        df = pd.read_csv(f"{ROOT}/{p}", index_col=0)
        df.index = pd.to_datetime(df.index)
        c = "ret" if "ret" in df.columns else df.columns[0]
        return df[c].astype(float)
    import io
    import subprocess
    rel = f"software/world-trader/{p}"
    blob = subprocess.run(["git", "-C", ROOT, "show", f"HEAD:{rel}"],
                          capture_output=True, check=True).stdout
    df = pd.read_csv(io.BytesIO(blob), index_col=0)
    df.index = pd.to_datetime(df.index)
    c = "ret" if "ret" in df.columns else df.columns[0]
    return df[c].astype(float)


def champion_weights():
    """Rebuild (net, Wg) with the canonical builder arithmetic; pin net to the committed
    champion CSV. Returns (max_abs_diff, Wg DataFrame)."""
    df = pd.DataFrame({n: load_sleeve(PATHS[n]).dropna() for n in NAMES})
    df = df[df.index >= '2008-03-31']
    isr = df[df.index < IS_END]
    SR = pd.Series({n: (lambda r: 0.0 if len(r.dropna()) < 200 or r.dropna().std(ddof=1) <= 1e-12
                        else float(r.dropna().mean() / r.dropna().std(ddof=1) * np.sqrt(252)))(isr[n])
                    for n in NAMES})
    relw = np.maximum(SR, 0.0) ** P
    nav = (1 + df.fillna(0)).cumprod().shift(1).fillna(1.0)
    d2 = nav.div(nav.mean(axis=1), axis=0).mul(relw, axis=1)
    d2 = d2.div(d2.sum(axis=1), axis=0) * len(NAMES)
    Wg = d2 * (GEAR / len(NAMES))
    port = (df.fillna(0).values * Wg.values).sum(axis=1)
    to = (Wg.diff().abs().sum(axis=1)).fillna(0.0)
    net = (pd.Series(port, index=df.index) - to * BPS / 1e4
           - np.maximum(GEAR - 1, 0) * RATE / ANN)
    committed = pd.read_csv(f"{ROOT}/campaign/results/GOAL100_RAWEW13v2_WEIGHTED_GEAR16_daily.csv",
                            index_col=0, parse_dates=True).iloc[:, 0]
    j = pd.concat([committed.rename('c'), net.rename('n')], axis=1, join='inner').dropna()
    return float((j.c - j.n).abs().max()), Wg


