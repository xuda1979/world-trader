def _fred(name, src=f"{ROOT}/tools/quant/hedge_fund_strats/data_fred"):
    df = pd.read_csv(f"{src}/{name}.csv", index_col=0, parse_dates=True)
    s = df['value'] if 'value' in df.columns else df.iloc[:, 0]
    return pd.to_numeric(s, errors='coerce').dropna().sort_index()


def _revalidate(name, pos_ret_rebuilt, tol=2e-4):
    """Re-net a reconstructed (pos*ret) path and compare to the committed sleeve CSV.
    Returns max|diff| on the inner join (float/CSV round-trip tolerance 2e-4)."""
    pos, ret = pos_ret_rebuilt
    raw = (pos * ret).dropna()
    from campaign.agents.B2_highfreq.gates import vol_target
    sc, _ = vol_target(raw)
    rebuilt = sc.dropna()
    committed = load_sleeve(PATHS[name]).dropna()
    j = pd.concat([committed.rename('c'), rebuilt.rename('n')], axis=1, join='inner').dropna()
    if len(j) == 0:
        return None
    return float((j.c - j.n).abs().max()), len(j)


def short_exposures():
    """Per-slot short-notional fraction stream |short pos| (before champion scaling),
    in units of '1.0 = sleeve fully short'. Returns {slot: Series}."""
    out = {}
    # brwt family (lb 15 from 2000, 10 from 2000, 7/5 from 2008): z-rev on brent-wti log spread
    BR = _fred('brent').dropna()
    WT = _fred('wti_full').dropna()
    sp = (np.log(BR) - np.log(WT)).dropna()
    for lb, min_start, key in ((15, '2000-01-01', 'brwt15'), (10, '2000-01-01', 'brwt10'),
                               (7, '2008-01-01', 'brwt7'), (5, '2008-01-01', 'brwt5')):
        s = sp[sp.index >= min_start]
        z = (s - s.rolling(lb, min_periods=lb).mean()) / s.rolling(lb, min_periods=lb).std().replace(0, np.nan)
        pos = pd.Series(0.0, index=s.index)
        pos[z < -1.5] = 1.0
        pos[z > 1.5] = -1.0
        out[key] = (-pos.clip(upper=0.0))
    # C5ng / C5ngsum: Wed/Thu short, Fri long, calm-filtered (k=2.5)
    s = pd.read_csv(f"{ROOT}/tools/quant/data/newdata/DHHNGSP.csv",
                    index_col=0, parse_dates=True).iloc[:, 0]
    s = pd.to_numeric(s, errors='coerce')
    s = s[s > 0].dropna().sort_index()
    lr = np.log(s).diff()
    for summer, key in ((False, 'C5ng'), (True, 'C5ngsum')):
        pos = pd.Series(0.0, index=lr.index)
        pos[lr.index.dayofweek == 2] = -1.0
        pos[lr.index.dayofweek == 3] = -1.0
        pos[lr.index.dayofweek == 4] = 1.0
        if summer:
            pos[~lr.index.month.isin(list(range(4, 11)))] = 0.0
        thr = lr.rolling(90).std().shift(1) * 2.5
        pos = pos.mask(lr.abs() > thr, 0.0)
        out[key] = (-pos.clip(upper=0.0))
    # carryv2 leg1: WTI-Brent spot spread z-rev (sign(-z), |z|>0.75 hold / 1.0 entry)
    wti = _fred('wti_full').reindex(_fred('brent').index)
    w = wti.where(wti.notna() & _fred('brent').notna()).ffill()
    b = _fred('brent').where(w.notna()).ffill()
    bad = ((w < 5) | (b < 5)).fillna(True)
    spr = (w - b).mask(bad)
    z = (spr - spr.rolling(126).mean()) / spr.rolling(126).std()
    psp = np.sign(-z).where(z.abs() > 1.0, np.nan)
    psp = psp.where(z.abs() > 0.75, 0).ffill().fillna(0).shift(1).fillna(0)
    psp = psp.where(~(bad | bad.shift(1).fillna(True)), 0.0)
    out['carryv2'] = (-psp.clip(upper=0.0))
    # a6r7: synthetic 2y TR, long-only when trend up -> no short days
