# line-level framing markers that make a stale-number mention historical rather than current
FRAME = re.compile(
    r"archive|leak|prior|supersede|counterfactual|\bvs\b|\bvs\.|\bold\b|history|was\b|"
    r"pre-|re-emit|rebuilt|sameday|SAMEDAYLEAK|honest-lagged|then\b|formerly",
    re.I,
)
# line-level markers that make a TRUTH20Y mention a provenance warning rather than a promotion
TRUTH_FRAME = re.compile(
    r"archive|supersede|not a champion|untracked|provenance|quarantine|breach|no builder|"
    r"do not (promote|quote)|never|external|legacy|flag",
    re.I,
)
STALE_RE = re.compile(
    r"(?i)ann[^\n]{0,40}\b(" + "|".join(STALE_HEADLINES).replace(".", r"\.") + r")\b"
)


def _gated_docs():
    docs = sorted(glob.glob(f"{ROOT}/campaign/*.md") + glob.glob(f"{ROOT}/campaign/results/*.md"))
    return [d for d in docs if not d.endswith(".pytest_cache/README.md")]


def _current_headline_pct():
    """Current champion headline, ann_geo campaign convention, computed from the committed CSV."""
    r = pd.read_csv(CHAMP, index_col=0, parse_dates=True).iloc[:, 0].dropna()
    return float((1 + r).prod() ** (252 / len(r)) - 1) * 100


def _stale_hits(text):
    hits = []
    for i, line in enumerate(text.splitlines(), 1):
        if STALE_RE.search(line) and not FRAME.search(line):
            hits.append((i, line.strip()[:110]))
    return hits


def _has_current_banner(text):
    m = re.search(r"SUPERSEDE[^\n]*", text, re.I)
    if not m:
        return False
    banner = text[max(0, m.start() - 200): m.start() + 2000]
    return f"{_current_headline_pct():.2f}%" in banner


