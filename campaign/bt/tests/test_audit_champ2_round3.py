def test_a1_no_gated_doc_bills_a_superseded_headline_as_current():
    offenders = {}
    for d in _gated_docs():
        text = open(d).read()
        hits = _stale_hits(text)
        if hits and not _has_current_banner(text):
            offenders[os.path.relpath(d, ROOT)] = hits
    assert not offenders, (
        "STALE HEADLINE billed as CURRENT (fix: additive SUPERSEDE banner naming "
        f"{_current_headline_pct():.2f}%):\n"
        + "\n".join(f"  {k}:{ln}: {s}" for k, v in offenders.items() for ln, s in v)
    )


def test_a2_no_gated_doc_quotes_truth20y_as_champion():
    offenders = []
    for d in _gated_docs():
        for i, line in enumerate(open(d).read().splitlines(), 1):
            if "TRUTH20Y" in line and not TRUTH_FRAME.search(line):
                offenders.append(f"{os.path.relpath(d, ROOT)}:{i}: {line.strip()[:110]}")
    assert not offenders, (
        "TRUTH20Y quoted without provenance/breach framing (it is NOT a champion: "
        "MDD -7.88% breaches the -7% wall, 1 neg year 2006, no builder in-tree):\n"
        + "\n".join(offenders)
    )


