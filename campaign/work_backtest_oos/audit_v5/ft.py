import pandas as pd, numpy as np, json, os, re, pickle, warnings
warnings.filterwarnings("ignore")
with open("shared_data.pkl","rb") as f: D=pickle.load(f)
sleeves=D["sleeves"]; w=D["w"]; df=D["df"]; isdf=D["isdf"]; osdf=D["osdf"]; ddf=D["ddf"]
ROOT=D["ROOT"]; OD=D["OD"]; IS_END=pd.Timestamp("2017-01-01")
def sr(r,freq=12):
    r=r.dropna(); r=r[r.abs()<0.5]
    return r.mean()/r.std()*np.sqrt(freq) if len(r)>1 and r.std()>0 else 0
pis=isdf[sleeves].dot(w); pos=osdf[sleeves].dot(w); pfs=df[sleeves].dot(w)
dport=ddf[sleeves].dot(w)
d_dd16=((1+dport*1.6).cumprod()/(1+dport*1.6).cumprod().cummax()-1).min()*100
m_dd_full=((1+pfs).cumprod()/(1+pfs).cumprod().cummax()-1).min()*100
m_dd_oos=((1+pos).cumprod()/(1+pos).cumprod().cummax()-1).min()*100
m_dd_is=((1+pis).cumprod()/(1+pis).cumprod().cummax()-1).min()*100
h1=pos[pos.index<"2021-01-01"]; h2=pos[pos.index>="2021-01-01"]
yr_full=pfs.groupby(pfs.index.year).apply(lambda x:(1+x).prod()-1)
yr_oos=pos.groupby(pos.index.year).apply(lambda x:(1+x).prod()-1)
wf_srs=[]
for fs in range(2012,2022):
    oos_s=pd.Timestamp(str(fs+5)+"-01-01"); oos_e=pd.Timestamp(str(fs+6)+"-01-01")
    win=df[sleeves][(df.index>=oos_s)&(df.index<oos_e)]
    if len(win)>=6: wf_srs.append(sr(win.dot(w)))
loo_srs=[]
for i in range(len(sleeves)):
    mask=[j for j in range(len(sleeves)) if j!=i]
    wl=w.values[mask]/w.values[mask].sum()
    loo_srs.append(sr(osdf[[sleeves[j] for j in mask]].dot(wl)))
ENP=re.compile(r"(crack|diesel|diescrack|_ho_|hobr|ng_storage|C5ng|brent|wti|prop|seas_12-02|gas_prem|DBE|DBP|_ng[_.]|/ng_)",re.I)
en_flags=[bool(ENP.search(os.path.basename(s))) for s in sleeves]
en_exp=sum(w.values[i]*en_flags[i] for i in range(len(sleeves)))
corr_is=isdf[sleeves].corr()
upper_is=corr_is.where(np.triu(np.ones(corr_is.shape),k=1).astype(bool))
mc_is=upper_is.stack().mean()
corr_oos=osdf[sleeves].corr()
upper_oos=corr_oos.where(np.triu(np.ones(corr_oos.shape),k=1).astype(bool))
mc_oos=upper_oos.stack().mean()
corr_daily=ddf[ddf.index<IS_END][sleeves].corr()
upper_d=corr_daily.where(np.triu(np.ones(corr_daily.shape),k=1).astype(bool))
mc_d=upper_d.stack().mean()
hhi=(w**2).sum(); eff_n=1/hhi
sleeve_vols=isdf[sleeves].std()*np.sqrt(12)
dr=(w*sleeve_vols).sum()/(isdf[sleeves].dot(w).std()*np.sqrt(12))
cov=isdf[sleeves].cov().values
from numpy.linalg import eig
ev,_=eig(cov); ev=np.sort(ev)[::-1].real
pc1=ev[0]/ev.sum(); eff_n_pca=ev.sum()**2/(ev**2).sum()
qly=pfs.resample("QE").apply(lambda x:(1+x).prod()-1 if len(x)>0 else 0)
pos_months=(pfs>0).mean()
print("PART2 OK")

