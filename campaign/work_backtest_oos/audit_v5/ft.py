    out.write(f"Worst year (OOS):    {yr_oos.min()*100:.2f}%"+chr(10))
    out.write(f"Best year (OOS):     {yr_oos.max()*100:.2f}%"+chr(10))
    out.write(f"Yearly std:          {yr_full.std()*100:.2f}%"+chr(10))
